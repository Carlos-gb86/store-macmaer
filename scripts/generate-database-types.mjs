import { writeFile } from "node:fs/promises";
import { createTestDatabase } from "./database.mjs";
const db = await createTestDatabase();
try {
  const { rows } =
    await db.query(`select c.table_name, c.column_name, c.is_nullable, c.column_default, c.data_type, c.udt_name, t.table_type
    from information_schema.columns c join information_schema.tables t on c.table_schema=t.table_schema and c.table_name=t.table_name
    where c.table_schema='public' order by c.table_name, c.ordinal_position`);
  const { rows: enums } = await db.query(
    `select t.typname, e.enumlabel from pg_type t join pg_enum e on e.enumtypid=t.oid order by e.enumsortorder`,
  );
  const enumMap = new Map();
  for (const row of enums)
    enumMap.set(row.typname, [
      ...(enumMap.get(row.typname) ?? []),
      row.enumlabel,
    ]);
  const scalar = (row) =>
    enumMap.has(row.udt_name)
      ? enumMap
          .get(row.udt_name)
          .map((v) => JSON.stringify(v))
          .join(" | ")
      : [
            "integer",
            "bigint",
            "smallint",
            "numeric",
            "double precision",
          ].includes(row.data_type)
        ? "number"
        : row.data_type === "boolean"
          ? "boolean"
          : row.data_type === "jsonb"
            ? "Json"
            : "string";
  let output =
    "// Generated by npm run db:types from the checked-in migrations using PostgreSQL introspection.\n";
  output +=
    "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: {\n";
  for (const group of ["Tables", "Views"]) {
    output += group + ": {\n";
    for (const name of [
      ...new Set(
        rows
          .filter((r) => (r.table_type === "VIEW") === (group === "Views"))
          .map((r) => r.table_name),
      ),
    ]) {
      const columns = rows.filter((r) => r.table_name === name);
      output += JSON.stringify(name) + ": {\n";
      for (const shape of group === "Views"
        ? ["Row"]
        : ["Row", "Insert", "Update"]) {
        output += shape + ": {\n";
        for (const row of columns)
          output +=
            JSON.stringify(row.column_name) +
            (shape === "Update" ||
            (shape === "Insert" &&
              (row.is_nullable === "YES" || row.column_default !== null))
              ? "?"
              : "") +
            ": " +
            scalar(row) +
            (row.is_nullable === "YES" ? " | null" : "") +
            ";\n";
        output += "};\n";
      }
      // Read model queries intentionally do not depend on SDK relationship inference.
      output += "Relationships: [];\n};\n";
    }
    output += "};\n";
  }
  output += "Functions: {\n";
  const { rows: functions } = await db.query(
    "select p.proname, p.proargnames, p.pronargdefaults, array(select format_type(t,null) from unnest(p.proargtypes) t) as arg_types, format_type(p.prorettype,null) as result_type from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and (p.proname='is_admin' or p.proname like 'admin_%' or p.proname like 'checkout_%') order by p.proname",
  );
  const functionType = (type) =>
    type === "jsonb"
      ? "Json"
      : type === "boolean"
        ? "boolean"
        : type === "void"
          ? "undefined"
          : "string";
  for (const fn of functions) {
    if (!fn.arg_types.length) {
      output +=
        JSON.stringify(fn.proname) +
        ": { Args: Record<never, never>; Returns: " +
        functionType(fn.result_type) +
        "};\n";
      continue;
    }
    output += JSON.stringify(fn.proname) + ": { Args: {";
    for (const [i, type] of fn.arg_types.entries())
      output +=
        JSON.stringify(fn.proargnames[i]) +
        (i >= fn.arg_types.length - fn.pronargdefaults ? "?" : "") +
        ": " +
        functionType(type) +
        ";";
    output += "}; Returns: " + functionType(fn.result_type) + "};\n";
  }
  output += "}; Enums: {\n";
  for (const [name, values] of enumMap)
    output +=
      JSON.stringify(name) +
      ": " +
      values.map((v) => JSON.stringify(v)).join(" | ") +
      ";\n";
  output += "}; CompositeTypes: Record<never, never>; }; };\n";
  await writeFile(
    new URL("../src/lib/supabase/database.types.ts", import.meta.url),
    output,
  );
} finally {
  await db.close();
}
